export function useI18n() {
  const locale = useCookie<Locale>('bc_locale', {
    default: () => 'es',
    sameSite: 'lax',
    secure: !import.meta.dev,
    maxAge: 60 * 60 * 24 * 365,
  });
  if (locale.value !== 'es' && locale.value !== 'en') locale.value = normalizeLocale(locale.value);

  function currentLocale(): Locale {
    return normalizeLocale(locale.value);
  }

  function t(key: string, values: TranslationValues = {}): string {
    const message = messages[currentLocale()][key] || messages.es[key] || key;
    return message.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
  }

  function setLocale(nextLocale: Locale) {
    locale.value = normalizeLocale(nextLocale);
  }

  function statusLabel(status: string | null | undefined): string {
    if (!status) return t('common.unknown');
    const key = `status.${status}`;
    return messages[currentLocale()][key] ? t(key) : status;
  }

  function stageTypeLabel(stageType: string): string {
    const format = STAGE_FORMATS.find((candidate) => candidate.value === stageType);
    return format ? t(format.labelKey) : stageType;
  }

  function errorMessage(cause: unknown, fallback: string): string {
    const failure = cause as {
      data?: { detail?: unknown };
      status?: number;
      statusCode?: number;
      name?: string;
      message?: string;
    };
    const detail = failure.data?.detail;
    if (locale.value === 'es' && typeof detail === 'string') return detail;
    if (failure.status === 401 || failure.statusCode === 401) return t('error.sessionExpired');
    if (failure.status === 403 || failure.statusCode === 403) return t('error.forbidden');
    if (failure.name === 'FetchError' && /timeout|abort/i.test(failure.message || '')) return t('error.timeout');
    if (failure.name === 'FetchError' || failure.name === 'TypeError') return t('error.network');
    if (!failure.data && !failure.status && !failure.statusCode && cause instanceof Error) return cause.message;
    return fallback;
  }

  const dateLocale = computed(() => locale.value === 'es' ? 'es-CO' : 'en-US');

  return { locale, dateLocale, t, setLocale, statusLabel, stageTypeLabel, errorMessage };
}
