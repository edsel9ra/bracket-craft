BEGIN;

-- ============================================================================
-- 025 — Team crests (additive)
--
-- Stores the private object key of the single crest image a team may have and
-- exposes the public team projection that the four anonymous surfaces read
-- (tournament detail, standings, matches and lineups) (RF-38, RF-47, RF-49).
--
--   * Additive only: one nullable column on `public.teams` and one new view.
--     No table, row, policy, index, function or existing view is rewritten.
--   * `teams.crest_object_key TEXT` is nullable and has no default: «no crest»
--     is NULL, the key is generated by the system (never by the person) and it
--     is always located through the `teams.id` primary key, so no index and no
--     length limit are added.
--   * Privileges: `teams` already grants SELECT, INSERT, UPDATE and DELETE to
--     `bracket_app` at table level (`init/01_schema.sql`), so the new column
--     inherits them. No column-level grant is added and `init/01` is not
--     touched.
--   * RLS: `teams` is tenant-owned and keeps its `tenant_isolation_policy` and
--     `FORCE ROW LEVEL SECURITY`; the column inherits both. No policy is added.
--   * `v_public_tournament_teams` follows exactly the visibility condition of
--     `v_public_tournaments`: published version, tournament in
--     `published`/`live`/`finished` and active organization. It is a
--     `security_barrier` projection owned by the migration role (exempt from
--     RLS), like `v_public_standings`/`v_public_matches`; `PUBLIC` gets no
--     privilege and only `bracket_app` may select it. It never exposes
--     `logo_url`, documents, ages or birth dates (RF-48, RF-51).
--   * No backfill: the column arrives NULL on every existing team, so the
--     legacy `logo_url` keeps its meaning until the first confirmed upload
--     (the application writes it, not the migration).
--   * No pre-check and no `VALIDATE CONSTRAINT`: there is no data rewrite and
--     no new constraint.
--   * Deployment order: 024 (PR #10) -> 025 -> the backend that reads and
--     writes the column. The previous image ignores the nullable column and
--     keeps working; the new code fails against schema 023, so the migration
--     goes first. There is no rollback: any defect is fixed with a new
--     migration (forward-fix). The clean volume (init/00-03 -> 001-025) ends
--     with the same schema as a migrated database.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. The crest reference. One image per team, shared by every tournament the
--    team is enrolled in; the image itself lives in the private storage.
-- ----------------------------------------------------------------------------
ALTER TABLE public.teams
    ADD COLUMN crest_object_key TEXT;

-- ----------------------------------------------------------------------------
-- 2. The public team projection. One row per enrolled team of a publicly
--    visible tournament; `crest_object_key` is NULL when the team has no crest.
-- ----------------------------------------------------------------------------
CREATE VIEW public.v_public_tournament_teams
WITH (security_barrier = true) AS
SELECT DISTINCT
       tr.id AS tournament_id,
       t.id  AS team_id,
       t.name,
       t.short_code,
       t.crest_object_key
FROM public.tournament_teams tt
JOIN public.tournaments tr
  ON tr.id = tt.tournament_id AND tr.organization_id = tt.organization_id
JOIN public.organizations org
  ON org.id = tr.organization_id AND org.is_active = TRUE
JOIN public.tournament_versions tv
  ON tv.id = tr.published_version_id
 AND tv.organization_id = tr.organization_id
 AND tv.tournament_id = tr.id
 AND tv.status = 'published'
JOIN public.teams t
  ON t.id = tt.team_id AND t.organization_id = tt.organization_id
WHERE tr.status IN ('published', 'live', 'finished');

REVOKE ALL ON public.v_public_tournament_teams FROM PUBLIC;
GRANT SELECT ON public.v_public_tournament_teams TO bracket_app;

COMMIT;
