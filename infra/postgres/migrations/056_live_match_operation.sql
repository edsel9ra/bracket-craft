CREATE TABLE IF NOT EXISTS public.match_live_state (
    match_id UUID NOT NULL,
    organization_id UUID NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
    content_revision BIGINT NOT NULL DEFAULT 0 CHECK (content_revision >= 0 AND content_revision <= revision),
    home_score INTEGER NOT NULL DEFAULT 0 CHECK (home_score >= 0),
    away_score INTEGER NOT NULL DEFAULT 0 CHECK (away_score >= 0),
    segment_id UUID,
    clock_state TEXT NOT NULL DEFAULT 'not_started' CHECK (clock_state IN ('not_started','running','paused')),
    clock_elapsed_us BIGINT NOT NULL DEFAULT 0 CHECK (clock_elapsed_us >= 0),
    clock_anchor_at TIMESTAMPTZ,
    initialized_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    frozen_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by_member_id UUID NOT NULL,
    PRIMARY KEY (match_id, organization_id),
    FOREIGN KEY (match_id, organization_id) REFERENCES public.matches(id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (segment_id, match_id, organization_id) REFERENCES public.match_segments(id, match_id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (updated_by_member_id, organization_id) REFERENCES public.organization_users(id, organization_id) ON DELETE RESTRICT,
    CHECK ((clock_state = 'not_started' AND segment_id IS NULL AND clock_elapsed_us = 0 AND clock_anchor_at IS NULL)
        OR (clock_state = 'paused' AND segment_id IS NOT NULL AND clock_anchor_at IS NULL)
        OR (clock_state = 'running' AND segment_id IS NOT NULL AND clock_anchor_at IS NOT NULL)),
    CHECK (frozen_at IS NULL OR clock_state <> 'running')
);

CREATE TABLE IF NOT EXISTS public.match_live_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL,
    match_id UUID NOT NULL,
    client_event_id UUID NOT NULL,
    segment_id UUID NOT NULL,
    team_id UUID NOT NULL,
    beneficiary_team_id UUID,
    player_id UUID NOT NULL,
    player_out_id UUID,
    player_in_id UUID,
    assist_player_id UUID,
    event_type TEXT NOT NULL CHECK (event_type IN ('goal','own_goal','penalty_goal','yellow_card','red_card','substitution','foul')),
    minute INTEGER NOT NULL CHECK (minute BETWEEN 0 AND 180),
    added_minute INTEGER NOT NULL DEFAULT 0 CHECK (added_minute BETWEEN 0 AND 30),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    event_order BIGINT GENERATED BY DEFAULT AS IDENTITY,
    removed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (organization_id, match_id, client_event_id),
    FOREIGN KEY (match_id, organization_id) REFERENCES public.match_live_state(match_id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (segment_id, match_id, organization_id) REFERENCES public.match_segments(id, match_id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (team_id, organization_id) REFERENCES public.teams(id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (beneficiary_team_id, organization_id) REFERENCES public.teams(id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (player_id, organization_id) REFERENCES public.players(id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (player_out_id, organization_id) REFERENCES public.players(id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (player_in_id, organization_id) REFERENCES public.players(id, organization_id) ON DELETE RESTRICT,
    FOREIGN KEY (assist_player_id, organization_id) REFERENCES public.players(id, organization_id) ON DELETE RESTRICT,
    CHECK ((event_type = 'substitution' AND player_out_id IS NOT NULL AND player_in_id IS NOT NULL
            AND player_out_id <> player_in_id AND player_id = player_out_id)
        OR (event_type <> 'substitution' AND player_out_id IS NULL AND player_in_id IS NULL)),
    CHECK ((event_type = 'own_goal' AND beneficiary_team_id IS NOT NULL AND beneficiary_team_id <> team_id)
        OR (event_type <> 'own_goal' AND beneficiary_team_id IS NULL)),
    CHECK (assist_player_id IS NULL OR (event_type = 'goal' AND assist_player_id <> player_id)),
    CHECK (metadata = '{}'::jsonb OR (event_type = 'red_card' AND metadata IN (
        '{"red_card_type":"direct_red"}'::jsonb, '{"red_card_type":"double_yellow_red"}'::jsonb)))
);

