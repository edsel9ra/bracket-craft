CREATE OR REPLACE FUNCTION public.match_live_has_permission(p_organization_id UUID, p_match_id UUID, p_permission TEXT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY INVOKER SET search_path = pg_catalog, public AS $$
    SELECT public.fn_verify_user_org_membership(p_organization_id) AND EXISTS (
        SELECT 1 FROM public.organization_users ou
        JOIN public.organization_user_roles our ON our.organization_user_id = ou.id AND our.organization_id = ou.organization_id
        JOIN public.roles r ON r.id = our.role_id AND r.organization_id = our.organization_id
        LEFT JOIN public.role_definitions rd ON rd.id = r.role_definition_id
        WHERE ou.organization_id = p_organization_id AND ou.is_active
            AND ou.user_id = NULLIF(current_setting('app.current_user_id',true),'')::UUID
            AND r.permissions @> jsonb_build_array(p_permission)
            AND (rd.code IN ('owner','administrator','operator') OR EXISTS (
                SELECT 1 FROM public.match_officials mo WHERE mo.organization_id = ou.organization_id
                    AND mo.match_id = p_match_id AND mo.organization_user_id = ou.id)))
$$;
REVOKE ALL ON FUNCTION public.match_live_has_permission(UUID, UUID, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.match_live_has_permission(UUID, UUID, TEXT) TO bracket_app;

CREATE OR REPLACE FUNCTION public.validate_match_live_write()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, public AS $$
DECLARE
    m public.matches%ROWTYPE;
    s public.match_live_state%ROWTYPE;
    freeze_only BOOLEAN := FALSE;
BEGIN
    SELECT * INTO m FROM public.matches WHERE id = NEW.match_id AND organization_id = NEW.organization_id FOR UPDATE;
    IF NOT FOUND OR m.result_confirmed OR m.status NOT IN ('live','suspended') THEN
        RAISE EXCEPTION 'LIVE_MATCH_NOT_EDITABLE' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND (NEW.match_id <> OLD.match_id OR NEW.organization_id <> OLD.organization_id) THEN
        RAISE EXCEPTION 'LIVE_IDENTITY_IMMUTABLE' USING ERRCODE = '23514';
    END IF;
    IF TG_TABLE_NAME = 'match_live_state' THEN
        IF TG_OP = 'UPDATE' THEN
            IF OLD.frozen_at IS NOT NULL THEN
                RAISE EXCEPTION 'LIVE_DRAFT_FROZEN' USING ERRCODE = '23514';
            END IF;
            freeze_only := NEW.frozen_at IS NOT NULL
                AND (to_jsonb(NEW) - ARRAY['frozen_at','updated_at','updated_by_member_id','clock_state','clock_elapsed_us','clock_anchor_at'])
                  = (to_jsonb(OLD) - ARRAY['frozen_at','updated_at','updated_by_member_id','clock_state','clock_elapsed_us','clock_anchor_at'])
                AND NEW.clock_state = CASE WHEN OLD.clock_state = 'not_started' THEN 'not_started' ELSE 'paused' END
                AND NEW.clock_anchor_at IS NULL
                AND NEW.clock_elapsed_us = OLD.clock_elapsed_us + CASE WHEN OLD.clock_state = 'running'
                    THEN (GREATEST(0, EXTRACT(EPOCH FROM (NEW.frozen_at - OLD.clock_anchor_at))) * 1000000)::BIGINT ELSE 0 END;
        END IF;
        IF NEW.clock_state = 'running' AND (m.status <> 'live' OR NOT EXISTS (
            SELECT 1 FROM public.match_segments ms WHERE ms.id = NEW.segment_id AND ms.match_id = NEW.match_id
                AND ms.organization_id = NEW.organization_id AND ms.status = 'active')) THEN
            RAISE EXCEPTION 'LIVE_CLOCK_SEGMENT_NOT_ACTIVE' USING ERRCODE = '23514';
        END IF;
        IF m.status = 'suspended' AND NOT freeze_only THEN
            RAISE EXCEPTION 'LIVE_MATCH_SUSPENDED' USING ERRCODE = '23514';
        END IF;
        IF NEW.frozen_at IS NOT NULL AND (NOT freeze_only
            OR NOT public.match_live_has_permission(NEW.organization_id,NEW.match_id,'VIEW_MATCH_LIVE_DRAFT')
            OR NOT public.match_live_has_permission(NEW.organization_id,NEW.match_id,'CLOSE_MATCH_REPORT')) THEN
            RAISE EXCEPTION 'LIVE_FREEZE_NOT_AUTHORIZED' USING ERRCODE = '42501';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM public.organization_users ou WHERE ou.id = NEW.updated_by_member_id
            AND ou.organization_id = NEW.organization_id AND ou.user_id = NULLIF(current_setting('app.current_user_id',true),'')::UUID) THEN
            RAISE EXCEPTION 'LIVE_ACTOR_MISMATCH' USING ERRCODE = '42501';
        END IF;
    ELSE
        SELECT * INTO s FROM public.match_live_state WHERE match_id = NEW.match_id AND organization_id = NEW.organization_id FOR UPDATE;
        IF NOT FOUND OR s.frozen_at IS NOT NULL THEN
            RAISE EXCEPTION 'LIVE_DRAFT_FROZEN' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_TABLE_NAME = 'match_live_reviews' THEN
        IF NOT public.match_live_has_permission(NEW.organization_id,NEW.match_id,'VIEW_MATCH_LIVE_DRAFT')
            OR NOT public.match_live_has_permission(NEW.organization_id,NEW.match_id,'CLOSE_MATCH_REPORT') THEN
            RAISE EXCEPTION 'LIVE_REVIEW_NOT_AUTHORIZED' USING ERRCODE = '42501';
        END IF;
    ELSIF NOT public.match_live_has_permission(NEW.organization_id,NEW.match_id,'OPERATE_MATCH_LIVE')
        AND NOT (freeze_only AND public.match_live_has_permission(NEW.organization_id,NEW.match_id,'VIEW_MATCH_LIVE_DRAFT')
            AND public.match_live_has_permission(NEW.organization_id,NEW.match_id,'CLOSE_MATCH_REPORT')) THEN
        RAISE EXCEPTION 'LIVE_OPERATION_NOT_AUTHORIZED' USING ERRCODE = '42501';
    END IF;
    IF TG_TABLE_NAME = 'match_live_events' THEN
        IF m.status <> 'live' OR NEW.team_id NOT IN (m.home_team_id,m.away_team_id)
            OR (NEW.beneficiary_team_id IS NOT NULL AND NEW.beneficiary_team_id NOT IN (m.home_team_id,m.away_team_id)) THEN
            RAISE EXCEPTION 'LIVE_EVENT_NOT_EDITABLE' USING ERRCODE = '23514';
        END IF;
        IF TG_OP = 'UPDATE' AND (NEW.id <> OLD.id OR NEW.client_event_id <> OLD.client_event_id
            OR NEW.event_order <> OLD.event_order OR NEW.created_at <> OLD.created_at) THEN
            RAISE EXCEPTION 'LIVE_IDENTITY_IMMUTABLE' USING ERRCODE = '23514';
        END IF;
        IF NEW.removed_at IS NULL AND (TG_OP = 'INSERT' OR OLD.removed_at IS NOT NULL) AND (
            SELECT count(*) FROM public.match_live_events WHERE match_id = NEW.match_id
                AND organization_id = NEW.organization_id AND removed_at IS NULL) >= 500 THEN
            RAISE EXCEPTION 'LIVE_EVENT_LIMIT' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_TABLE_NAME IN ('match_live_commands','match_live_reviews') THEN
        IF NOT EXISTS (SELECT 1 FROM public.user_sessions us WHERE us.id = NEW.session_id AND us.user_id = NEW.actor_user_id
            AND us.user_id = NULLIF(current_setting('app.current_user_id',true),'')::UUID
            AND us.revoked_at IS NULL AND us.expires_at > CURRENT_TIMESTAMP) THEN
            RAISE EXCEPTION 'LIVE_SESSION_MISMATCH' USING ERRCODE = '42501';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.validate_match_live_write() FROM PUBLIC, bracket_app;

DO $$
DECLARE table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['match_live_state','match_live_events','match_live_commands','match_live_reviews'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_validate_live_write ON public.%I', table_name);
        EXECUTE format('CREATE TRIGGER trg_validate_live_write BEFORE INSERT OR UPDATE ON public.%I
            FOR EACH ROW EXECUTE FUNCTION public.validate_match_live_write()', table_name);
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_match_live_transition()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, public AS $$
DECLARE s public.match_live_state%ROWTYPE;
BEGIN
    SELECT * INTO s FROM public.match_live_state WHERE match_id = OLD.id AND organization_id = OLD.organization_id;
    IF NOT FOUND THEN RETURN NEW; END IF;
    IF NEW.result_confirmed OR NEW.status IN ('finished','cancelled','administrative_resolution') THEN
        IF s.frozen_at IS NULL OR s.clock_state = 'running' THEN
            RAISE EXCEPTION 'LIVE_CLOSE_REQUIRES_FREEZE' USING ERRCODE = '23514';
        END IF;
    ELSIF (NEW.status <> OLD.status AND NOT ((OLD.status = 'live' AND NEW.status = 'suspended')
        OR (OLD.status = 'suspended' AND NEW.status = 'live')))
        OR (NEW.status = 'suspended' AND s.clock_state = 'running') THEN
        RAISE EXCEPTION 'LIVE_INVALID_TRANSITION' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.validate_match_live_transition() FROM PUBLIC, bracket_app;
DROP TRIGGER IF EXISTS trg_validate_match_live_transition ON public.matches;
CREATE TRIGGER trg_validate_match_live_transition BEFORE UPDATE OF status, result_confirmed ON public.matches
    FOR EACH ROW EXECUTE FUNCTION public.validate_match_live_transition();

CREATE OR REPLACE FUNCTION public.validate_match_live_segment()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, public AS $$
BEGIN
    PERFORM 1 FROM public.matches WHERE id = NEW.match_id AND organization_id = NEW.organization_id FOR UPDATE;
    IF NEW.status <> 'active' AND EXISTS (SELECT 1 FROM public.match_live_state
        WHERE segment_id = NEW.id AND match_id = NEW.match_id AND organization_id = NEW.organization_id
            AND clock_state = 'running') THEN
        RAISE EXCEPTION 'LIVE_CLOCK_SEGMENT_NOT_ACTIVE' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.validate_match_live_segment() FROM PUBLIC, bracket_app;
DROP TRIGGER IF EXISTS trg_validate_match_live_segment ON public.match_segments;
CREATE TRIGGER trg_validate_match_live_segment BEFORE UPDATE OF status ON public.match_segments
    FOR EACH ROW EXECUTE FUNCTION public.validate_match_live_segment();

CREATE OR REPLACE VIEW public.v_match_live_public_selection WITH (security_barrier = true) AS
SELECT m.id, m.tournament_id, m.stage_id, m.group_id, m.matchday, m.match_date,
    m.home_team_id, ht.name AS home_team_name, m.away_team_id, at.name AS away_team_name,
    m.status, ls.home_score, ls.away_score, TRUE AS is_provisional,
    ms.segment_number AS clock_segment_number,
    CASE WHEN ls.clock_state = 'not_started' THEN NULL ELSE
        (ls.clock_elapsed_us + CASE WHEN ls.clock_state = 'running' THEN
            (GREATEST(0, EXTRACT(EPOCH FROM (CURRENT_TIMESTAMP - ls.clock_anchor_at))) * 1000000)::BIGINT ELSE 0 END) / 1000000 END AS clock_elapsed_seconds,
    ls.clock_state, CURRENT_TIMESTAMP AS clock_observed_at
FROM public.matches m
JOIN public.match_live_state ls ON ls.match_id = m.id AND ls.organization_id = m.organization_id
JOIN public.tournaments t ON t.id = m.tournament_id AND t.organization_id = m.organization_id
JOIN public.organizations o ON o.id = m.organization_id AND o.is_active
JOIN public.tournament_versions tv ON tv.id = m.tournament_version_id AND tv.organization_id = m.organization_id
    AND tv.tournament_id = t.id AND tv.status = 'published'
JOIN public.stages st ON st.id = m.stage_id AND st.organization_id = m.organization_id
    AND st.tournament_id = t.id AND st.tournament_version_id = tv.id
JOIN public.teams ht ON ht.id = m.home_team_id AND ht.organization_id = m.organization_id
JOIN public.teams at ON at.id = m.away_team_id AND at.organization_id = m.organization_id
LEFT JOIN public.match_segments ms ON ms.id = ls.segment_id AND ms.match_id = m.id AND ms.organization_id = m.organization_id
WHERE t.status IN ('published','live','finished') AND m.tournament_version_id = t.published_version_id
    AND m.status IN ('live','suspended') AND NOT m.result_confirmed AND ls.frozen_at IS NULL;

